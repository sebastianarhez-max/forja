-- Verificación
SELECT h.id_horario, a.nombre AS actividad, s.nombre AS sala, h.dia, h.hora_inicio, h.hora_fin, h.cupo_maximo
FROM horario h JOIN actividad a ON a.id_actividad = h.id_actividad LEFT JOIN sala s ON s.id_sala = h.id_sala
