-- 1. Tabla sala
CREATE TABLE IF NOT EXISTS sala (
  id_sala     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(50) NOT NULL,
  capacidad   INT NOT NULL,
  descripcion TEXT,
  estado      BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_sala_nombre UNIQUE (nombre),
  CONSTRAINT chk_sala_capacidad CHECK (capacidad > 0)
);

-- 2. Cada clase (horario) puede dictarse en una sala
ALTER TABLE horario ADD COLUMN IF NOT EXISTS id_sala INT NULL;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_horario_sala') THEN
    ALTER TABLE horario ADD CONSTRAINT fk_horario_sala FOREIGN KEY (id_sala) REFERENCES sala(id_sala);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_horario_sala ON horario(id_sala);

